import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { audit, type AuditEntry } from "./audit.ts";

const resultsDir = join(dirname(fileURLToPath(import.meta.url)), "..", "results");
const failures: string[] = [];
const lines: string[] = [];

function out(text = ""): void {
  lines.push(text);
}

function check(claim: string, held: boolean, detail: string): boolean {
  if (!held) failures.push(claim + " - " + detail);
  console.log((held ? "  ok   " : "  FAIL ") + claim + (detail ? "  [" + detail + "]" : ""));
  return held;
}

function renderEntry(entry: AuditEntry): void {
  out("### " + entry.id + " - " + (entry.reducible ? "reducible to R" : "**not reducible to R**"));
  out("");
  out("**Constraint.** " + entry.constraint);
  out("");
  out("**Source.** " + entry.source);
  out("");
  out("**Reducible.** " + (entry.reducible ? "yes" : "no") + " - " + entry.reason);
  out("");
  if (entry.selfSustaining !== null) {
    out("**Self-sustaining.** " + (entry.selfSustaining ? "yes" : "**no**"));
    out("");
  }
  out("**Residual.** " + entry.residual);
  out("");
  out("**Method.** " + entry.method);
  out("");
  out("| Check | Held | Detail |");
  out("|-------|------|--------|");
  for (const c of entry.checks) {
    out("| " + c.claim + " | " + (c.held ? "yes" : "**NO**") + " | " + c.detail + " |");
  }
  out("");
}

function main(): void {
  const entries = audit();

  out("# Kernel Reduction Audit");
  out("");
  out("Generated by experiments/reduction/run.ts.");
  out("");
  out("The ATP-0002 freeze states eight constraints and calls the kernel");
  out("D = (S0, R0) with R(S, X, C, S') -> valid / invalid. This audit makes");
  out("'push this constraint into R' a literal operation (experiments/reduction/kernel.ts)");
  out("and then looks for constraints the operation cannot absorb.");
  out("");
  out("Two things are deliberately NOT tested, because they would be circular:");
  out("");
  out("1. whether a constraint can be written as a predicate on R's arguments - it always can,");
  out("   since the kernel imposes no shape on R;");
  out("2. whether the resulting domain is still 'ATP' - the freeze answers that by definition.");
  out("");
  out("The real question is narrower and answerable: **is there a constraint that constrains");
  out("which R is consulted, or how many domains exist, rather than what any R accepts?**");
  out("");

  // -------------------------------------------------------------------------
  console.log("Aggregate claims");
  const irreducible = entries.filter((e) => !e.reducible);
  const reducible = entries.filter((e) => e.reducible);
  const notSelfSustaining = entries.filter((e) => e.selfSustaining === false);

  check(
    "every stated check held",
    entries.every((e) => e.checks.every((c) => c.held)),
    entries.reduce((n, e) => n + e.checks.filter((c) => !c.held).length, 0) + " failed",
  );
  check(
    "most stated constraints do reduce to R",
    reducible.length >= 6,
    reducible.map((e) => e.id).join(", "),
  );
  check(
    "exactly two constraints resist reduction",
    irreducible.length === 2,
    irreducible.map((e) => e.id).join(", "),
  );
  check(
    "and the two are of different kinds",
    irreducible.length === 2 && irreducible[0].id !== irreducible[1].id,
    "C2 constrains the kernel's evaluation order; C5 constrains the number of domains",
  );
  check(
    "at least one reduction is not self-sustaining",
    notSelfSustaining.length >= 1,
    notSelfSustaining.map((e) => e.id).join(", "),
  );

  const c2 = entries.find((e) => e.id === "C2");
  check(
    "C2 is decided above any relation, not inside one",
    c2 !== undefined && !c2.reducible && c2.checks.some((c) => c.claim.includes("no relation can prevent it") && c.held),
    "the same relations produce different outcomes under the two evaluation orders",
  );
  const c5 = entries.find((e) => e.id === "C5");
  check(
    "C5 is an architectural residual, not a semantic one",
    c5 !== undefined && !c5.reducible && c5.checks.some((c) => c.claim.includes("invariant under arbitrary changes") && c.held),
    "no local relation can observe the other domain",
  );

  // -------------------------------------------------------------------------
  out("## Result");
  out("");
  out("| Constraint | Reducible to R | Self-sustaining | Residual |");
  out("|------------|----------------|-----------------|----------|");
  for (const entry of entries) {
    out(
      "| " + entry.id + " | " + (entry.reducible ? "yes" : "**no**") + " | " +
        (entry.selfSustaining === null ? "n/a" : entry.selfSustaining ? "yes" : "**no**") + " | " +
        entry.residual + " |",
    );
  }
  out("");
  out("Legend: " + entries.map((e) => e.id + " = " + e.constraint.slice(0, 60)).join("; "));
  out("");
  out("## Detail");
  out("");
  for (const entry of entries) renderEntry(entry);

  // -------------------------------------------------------------------------
  out("## Conclusion");
  out("");
  out("Of the eight constraints the freeze states, **six reduce to some R**, **one is");
  out("not a constraint on R at all**, and **one genuinely resists reduction**:");
  out("");
  out("- **C5 (shared uniqueness)** resists because a joint predicate over two independent");
  out("  domains is a function of both states, and no R receives both. The audit shows a");
  out("  domain's outcome is invariant under arbitrary changes to the other domain's state,");
  out("  so no local relation can enforce it. This is an **architectural** residual, and the");
  out("  freeze already states it: instantiate a shared domain. Real result, but not a kernel");
  out("  constraint.");
  out("- **C2 (semantic reflexivity)** resists for a different reason: it constrains *which*");
  out("  relation the kernel consults, and that choice is made above every relation. The audit");
  out("  holds the relations fixed and changes only the kernel's rule; the outcome flips from");
  out("  rejected to accepted, and no wrapping of any relation recovers it.");
  out("");
  out("### The kernel is not empty - it is exactly one rule");
  out("");
  out("~~~text");
  out("D = (S0, R0)");
  out("R(S, X, C, S') -> valid / invalid");
  out("evaluation: the semantics in force BEFORE the transition");
  out("~~~");
  out("");
  out("That third line is the whole kernel. It is what makes a domain unable to authorise");
  out("its own semantic replacement. Remove it and the kernel becomes empty, which the audit");
  out("demonstrates directly: with successor evaluation, the identical relation set accepts a");
  out("self-authorising semantic change.");
  out("");
  out("The freeze states this rule but files it as invariant 2 among semantic constraints,");
  out("alongside C1 (definitional), C3 (conditional on R and not self-sustaining), and C8");
  out("(a permission). Reading the invariant list, it looks like the kernel constrains a lot.");
  out("It constrains exactly one thing, and that thing is about evaluation order rather than");
  out("about meaning.");
  out("");
  out("### Weakest stated constraint");
  out("");
  out("C3 is reducible **and** not self-sustaining: the audit adopts a relation without the");
  out("constraint and then erases history, and nothing objects. The freeze hedges this already");
  out("('a semantic violation when the domain's rules prohibit such rewriting'), which concedes");
  out("the point. Historical integrity is a domain choice, not a kernel property.");
  out("");
  out("### Falsifiers");
  out("");
  out("This audit is refuted by any one of:");
  out("");
  out("1. a constraint that is not definitional, not a permission, not about composition, and");
  out("   not reducible to some R;");
  out("2. a demonstration that pre-state evaluation *can* be recovered from inside a relation,");
  out("   which would make C2 reducible and the kernel empty after all;");
  out("3. a joint constraint over independent domains that some pair of local relations does");
  out("   enforce, which would make C5 reducible and leave only C2.");
  out("");
  out("None was found here. The honest statement of the frozen result is therefore:");
  out("");
  out("> ATP-0002 reduces to one rule about evaluation order, plus a free relation.");
  out("> Everything else is definition, permission, or architecture.");
  out("");

  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, "reduction-audit.md"), lines.join("\n"), "utf8");
  console.log("");
  console.log("audit: " + (failures.length === 0 ? "all claims held" : failures.length + " claim(s) FAILED") + " -> experiments/results/reduction-audit.md");
  if (failures.length > 0) process.exitCode = 1;
}

main();
