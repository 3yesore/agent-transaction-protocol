import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  CLAUSES,
  CONTEXT,
  CORPUS,
  LADDER,
  MINIMAL_SPEC,
  TOTAL_SPEC,
  ambiguityBudget,
  classesCoveredBy,
  decide,
} from "./spec.ts";

const resultsDir = join(dirname(fileURLToPath(import.meta.url)), "..", "results");
const failures: string[] = [];
const lines: string[] = [];

function out(text = ""): void {
  lines.push(text);
}

function check(claim: string, held: boolean, detail: string): void {
  if (!held) failures.push(claim + " - " + detail);
  console.log((held ? "  ok   " : "  FAIL ") + claim + (detail ? "  [" + detail + "]" : ""));
}

function main(): void {
  out("# The Ambiguity Budget of an Amendment Specification");
  out("");
  out("Generated by experiments/amendment-ambiguity/run.ts.");
  out("");
  out("The meta-consensus study showed that diversity makes a self-amending chain worse once");
  out("a rule fork is expensive, and its third falsifier named the way out: an amendment");
  out("procedure with d = 0, unambiguous enough that independent clients cannot diverge. This");
  out("measures what it would take.");
  out("");
  out("A specification does not have to be wrong to fork a chain. It only has to be silent.");
  out("So the decision function here is three-valued:");
  out("");
  out("~~~text");
  out("valid | invalid | undetermined");
  out("~~~");
  out("");
  out("**undetermined** is the ambiguity, and it is exactly where two honest clients can");
  out("disagree. The quantity is d, the fraction of amendments the specification does not");
  out("decide.");
  out("");
  out("The corpus is " + CORPUS.length + " amendments covering the ways an amendment can be");
  out("defective. The specification is built from " + CLAUSES.length + " clauses, each one a");
  out("decision it must make explicitly.");
  out("");

  // -------------------------------------------------------------------------
  console.log("1. The ladder");
  out("## 1. The ladder");
  out("");
  out("Clauses added one at a time. Each rung must close at least one class.");
  out("");
  out("| spec | clauses stated | valid | invalid | undetermined | d | class closed |");
  out("|------|----------------|-------|---------|--------------|---|--------------|");

  const ladderStats: Array<{ spec: string[]; d: number; added: string }> = [];
  let spec: string[] = [...MINIMAL_SPEC];
  const minimal = ambiguityBudget(spec, CORPUS, CONTEXT);
  out("| minimal | 0 | " + minimal.valid + " | " + minimal.invalid + " | " + minimal.undetermined + " | " + (minimal.d * 100).toFixed(1) + "% | - |");
  ladderStats.push({ spec: [...spec], d: minimal.d, added: "-" });

  for (const clauseId of LADDER) {
    spec = [...spec, clauseId];
    const budget = ambiguityBudget(spec, CORPUS, CONTEXT);
    const covered = classesCoveredBy(clauseId).join(", ");
    out(
      "| + " + clauseId + " | " + spec.length + " | " + budget.valid + " | " + budget.invalid + " | " + budget.undetermined + " | " +
        (budget.d * 100).toFixed(1) + "% | " + covered + " |",
    );
    ladderStats.push({ spec: [...spec], d: budget.d, added: clauseId });
  }
  out("");

  check(
    "a minimal specification leaves most of the corpus undecided",
    minimal.d > 0.8,
    "d = " + (minimal.d * 100).toFixed(1) + "% with no clauses stated",
  );
  let strictlyFell = true;
  for (let index = 1; index < ladderStats.length; index++) {
    if (ladderStats[index].d >= ladderStats[index - 1].d) strictlyFell = false;
  }
  check("every rung strictly reduces the ambiguity budget", strictlyFell, ladderStats.map((s) => (s.d * 100).toFixed(1) + "%").join(" -> "));

  const total = ambiguityBudget(TOTAL_SPEC, CORPUS, CONTEXT);
  check(
    "a total specification has d = 0: every amendment is decided",
    total.d === 0 && total.undetermined === 0,
    total.valid + " valid, " + total.invalid + " invalid, 0 undetermined",
  );
  check(
    "and the conforming amendment is still accepted, so determinacy did not come from rejecting everything",
    decide(TOTAL_SPEC, CORPUS[0], CONTEXT).verdict === "valid",
    "the conforming entry is valid under the total specification",
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("2. What each class costs, and which clause owns it");
  out("## 2. What each class costs");
  out("");
  out("| class | amendment | minimal spec | total spec | clause that owns it |");
  out("|-------|-----------|--------------|------------|---------------------|");
  for (const item of CORPUS) {
    const before = decide(MINIMAL_SPEC, item, CONTEXT);
    const after = decide(TOTAL_SPEC, item, CONTEXT);
    out(
      "| " + item.className + " | " + item.id + " | " + before.verdict + " | " + after.verdict + " | " +
        (before.rejecting.length > 0 ? before.rejecting.join(", ") : "-") + " |",
    );
  }
  out("");

  const selfAuth = CORPUS.find((item) => item.id === "self-authorization")!;
  const selfBefore = decide(MINIMAL_SPEC, selfAuth, CONTEXT);
  const selfAfter = decide(TOTAL_SPEC, selfAuth, CONTEXT);
  check(
    "the kernel's own rule, left implicit, is an ambiguity class",
    selfBefore.verdict === "undetermined" && selfBefore.unresolved.includes("require-pre-state-authorization"),
    "a domain authorising its own replacement is undetermined under the minimal spec",
  );
  check(
    "and stating it turns that case invalid",
    selfAfter.verdict === "invalid",
    "the total spec rejects self-authorization: " + selfAfter.rejecting.join(", "),
  );
  check(
    "three distinct attack shapes are closed by that one clause",
    classesCoveredBy("require-pre-state-authorization").length === 3,
    classesCoveredBy("require-pre-state-authorization").join(", "),
  );
  check(
    "the wire-format clauses own classes that have nothing to do with the protocol",
    classesCoveredBy("require-canonical-encoding").length >= 3,
    classesCoveredBy("require-canonical-encoding").join(", "),
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("3. Encoding alone can fork a chain");
  out("## 3. Encoding alone can fork a chain");
  out("");
  const encodingClasses = CORPUS.filter((item) => item.className.startsWith("non-canonical"));
  out("Three amendments carry **identical semantic content** and differ only in their bytes:");
  out("");
  for (const item of encodingClasses) {
    out("- " + item.id + ": " + item.note);
  }
  out("");
  out("Under a specification that does not require canonical encoding, all three are");
  out("undetermined, so one client may accept a byte sequence another rejects while both agree");
  out("on what it MEANS. At the object level that is a rejected block. At the meta level it is a");
  out("split.");
  out("");
  check(
    "all three encoding variants are undetermined without a canonical-encoding clause",
    encodingClasses.every((item) => decide(MINIMAL_SPEC, item, CONTEXT).verdict === "undetermined"),
    encodingClasses.length + " variants",
  );
  check(
    "and a single clause closes all of them",
    encodingClasses.every((item) => decide(TOTAL_SPEC, item, CONTEXT).verdict === "invalid"),
    "one clause, " + encodingClasses.length + " classes",
  );

  // -------------------------------------------------------------------------
  out("## Conclusion");
  out("");
  out("**1. Ambiguity is measurable and it is the right quantity.** Not correctness - the");
  out("specification can be entirely correct and still leave a third of the corpus undecided,");
  out("because it never says what happens to a malformed amendment. d is that fraction, and it");
  out("is precisely where two honest clients diverge.");
  out("");
  out("**2. A total specification drives d to zero.** Stating the " + CLAUSES.length + " clauses gets");
  out("there, and it does so without rejecting the conforming case, so determinacy does not come");
  out("from blanket refusal.");
  out("");
  out("**3. The kernel's one rule must be written down, or the most important case is");
  out("undetermined.** With the rule implicit, a domain authorising its own replacement is not");
  out("invalid - it is undecided. Three distinct shapes (absent, wrong, self) are closed by");
  out("stating that one clause. This is the constructive counterpart to the freeze's own open");
  out("question: the only irreducible constraint is pre-state evaluation, and it is only a");
  out("constraint once it is explicit.");
  out("");
  out("**4. Encoding is a fork surface, not a detail.** Three amendments with identical meaning");
  out("and different bytes are enough to split clients that agree about semantics entirely. Canon-");
  out("ical encoding is not a serialization preference; it is part of the amendment procedure.");
  out("");
  out("That gives the chain a concrete design obligation rather than a hope: publish the");
  out("amendment decision procedure as a total function over a canonical encoding, ship a");
  out("conformance suite for it, and only then is diversity free again.");
  out("");

  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, "amendment-ambiguity.md"), lines.join("\n"), "utf8");
  console.log("");
  console.log("amendment-ambiguity: " + (failures.length === 0 ? "all claims held" : failures.length + " claim(s) FAILED") + " -> experiments/results/amendment-ambiguity.md");
  if (failures.length > 0) process.exitCode = 1;
}

main();
