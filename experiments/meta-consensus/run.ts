import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  amendmentCaptureRate,
  amendmentFloor,
  combinedLoss,
  formatPercent,
  independentCaptureRate,
  lifetimeCapture,
  metaForkProbability,
  optimalImplementations,
  quorumOf,
  simulatePersistence,
  type MetaConfig,
} from "./model.ts";
import { familySizes } from "../validator-quorum/model.ts";

const resultsDir = join(dirname(fileURLToPath(import.meta.url)), "..", "results");
const P = 0.15;
const RHO = 0.2;
const D = 0.02;

const failures: string[] = [];
const lines: string[] = [];

function out(text = ""): void {
  lines.push(text);
}

function check(claim: string, held: boolean, detail: string): void {
  if (!held) failures.push(claim + " - " + detail);
  console.log((held ? "  ok   " : "  FAIL ") + claim + (detail ? "  [" + detail + "]" : ""));
}

function config(over: Partial<MetaConfig> = {}): MetaConfig {
  return { validators: 35, implementations: 1, threshold: 18, commonModeRate: RHO, independentRate: P, interpretationDivergence: D, seed: 7, ...over };
}

function main(): void {
  out("# Semantic Amendment Under a Quorum");
  out("");
  out("Generated by experiments/meta-consensus/run.ts.");
  out("");
  out("ATP-0002's one rule is that a transition is evaluated under the semantics in force");
  out("BEFORE it, so an amendment R0 -> R1 must be authorised by R0. On a chain that means a");
  out("quorum selects it. This measures what changes when the thing being selected is the");
  out("rules themselves.");
  out("");
  out("An object-level transition is one of a stream. A semantic amendment is a single,");
  out("self-replacing, irreversible event. Three asymmetries follow.");
  out("");

  // -------------------------------------------------------------------------
  console.log("1. Frequency: the relevant quantity is lifetime capture, not per-round");
  out("## 1. Frequency");
  out("");
  out("A per-round shared cause is averaged away over a stream. Over N amendments it is not,");
  out("because the question is whether it coincides with ANY of them:");
  out("");
  out("~~~text");
  out("P(at least one capture) = 1 - (1 - p)^N");
  out("~~~");
  out("");
  out("Correlated: one client family, capture rate == the shared-cause rate. Independent: no");
  out("shared cause at all, so capture needs " + 18 + " of " + 35 + " validators to flip on their own.");
  out("");
  out("| amendments N | correlated (rho = 0.2) | independent (V=35, k=18, p=0.15) |");
  out("|--------------|------------------------|--------------------------------------|");
  const correlatedRate = RHO;
  const independentRate = independentCaptureRate(35, 18, P);
  for (const n of [1, 3, 5, 10, 21, 50]) {
    out("| " + n + " | " + formatPercent(lifetimeCapture(correlatedRate, n)) + " | " + formatPercent(lifetimeCapture(independentRate, n)) + " |");
  }
  out("");
  check(
    "one shared cause of 0.2 makes a lifetime capture near-certain within a handful of amendments",
    lifetimeCapture(correlatedRate, 3) > 0.48 && lifetimeCapture(correlatedRate, 21) > 0.99,
    "50% by N=" + Math.ceil(Math.log(0.5) / Math.log(1 - correlatedRate)) + ", " + formatPercent(lifetimeCapture(correlatedRate, 21)) + " by N=21",
  );
  check(
    "with no shared cause at all the same quorum is effectively immune",
    lifetimeCapture(independentRate, 50) < lifetimeCapture(correlatedRate, 50) / 10000,
    formatPercent(lifetimeCapture(independentRate, 50)) + " independent against " + formatPercent(lifetimeCapture(correlatedRate, 50)) + " correlated, over 50 amendments",
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("2. Persistence: capture is absorbing at the meta level");
  out("## 2. Persistence");
  out("");
  out("An object-level bad state is reversible under unchanged rules. A captured amendment");
  out("replaces the rules, so nothing in the new semantics is obliged to offer a way back.");
  out("");
  out("| N | object-level bad rounds | meta-level bad rounds | meta captures | ratio |");
  out("|---|-------------------------|-----------------------|---------------|-------|");
  const persistence = new Map<number, ReturnType<typeof simulatePersistence>>();
  for (const n of [10, 50, 100, 400]) {
    const result = simulatePersistence({ captureRate: correlatedRate, recoveryRate: 0.9, amendments: n, trials: 2000, seed: 5 });
    persistence.set(n, result);
    out(
      "| " + n + " | " + formatPercent(result.objectBadFraction) + " | " + formatPercent(result.metaBadFraction) + " | " +
        formatPercent(result.metaCaptureFraction) + " | " + result.ratio.toFixed(1) + "x |",
    );
  }
  out("");
  const p100 = persistence.get(100)!;
  const p400 = persistence.get(400)!;
  check(
    "the same per-amendment capture rate costs several times more at the meta level",
    p100.ratio > 4,
    formatPercent(p100.objectBadFraction) + " of rounds bad at the object level against " + formatPercent(p100.metaBadFraction) + " at the meta level",
  );
  check(
    "object-level badness stays bounded by the capture-to-recovery ratio",
    Math.abs(p400.objectBadFraction - 0.18) < 0.03,
    formatPercent(p400.objectBadFraction) + " at N=400; the closed form is p/(p+c) = " + (correlatedRate / (correlatedRate + 0.9)).toFixed(3),
  );
  check(
    "meta-level badness converges on nearly every round instead",
    p400.metaBadFraction > 0.98,
    formatPercent(p400.metaBadFraction) + " at N=400; the closed form is (N - 1/p)/N = " + ((400 - 5) / 400).toFixed(4),
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("3. Divergence: diversity helps the object level and hurts the meta level");
  out("## 3. Divergence");
  out("");
  out("Diversity lowers the object-level floor, because it de-correlates failures. It raises");
  out("the chance that implementations read R0 differently, and at the meta level a");
  out("disagreement about the rules is not a rejected transition - it is two rule sets.");
  out("");
  out("~~~text");
  out("P(fork) = 1 - (1 - d)^m");
  out("~~~");
  out("");
  out("35 validators, majority threshold, rho = 0.2, d = " + D + " per implementation.");
  out("");
  out("| implementations m | family split | object-level floor | P(meta fork) | loss, severity 1 | loss, severity 10 |");
  out("|-------------------|--------------|--------------------|--------------|------------------|-------------------|");
  const base: Omit<MetaConfig, "implementations"> = { validators: 35, threshold: 18, commonModeRate: RHO, independentRate: P, interpretationDivergence: D, seed: 7 };
  const candidates = [1, 2, 3, 5, 7, 12, 35];
  const floors = new Map<number, number>();
  const forks = new Map<number, number>();
  for (const m of candidates) {
    const cfg: MetaConfig = { ...base, implementations: m };
    const floor = amendmentFloor(cfg);
    const fork = metaForkProbability(cfg);
    floors.set(m, floor);
    forks.set(m, fork);
    out(
      "| " + m + " | " + familySizes(quorumOf(cfg)).join("+") + " | " + formatPercent(floor) + " | " + formatPercent(fork) + " | " +
        combinedLoss(cfg, 1).toFixed(3) + " | " + combinedLoss(cfg, 10).toFixed(3) + " |",
    );
  }
  out("");

  let floorMonotone = true;
  for (let index = 1; index < candidates.length; index++) {
    if (floors.get(candidates[index])! > floors.get(candidates[index - 1])! + 1e-9) floorMonotone = false;
  }
  let forkMonotone = true;
  for (let index = 1; index < candidates.length; index++) {
    if (forks.get(candidates[index])! < forks.get(candidates[index - 1])! - 1e-9) forkMonotone = false;
  }
  check("the object-level floor is non-increasing in diversity", floorMonotone, [1, 2, 3, 5, 7, 12, 35].map((m) => formatPercent(floors.get(m)!)).join(" >= "));
  check("the meta-level fork probability is strictly increasing in diversity", forkMonotone, [1, 2, 3, 5, 7, 12, 35].map((m) => formatPercent(forks.get(m)!)).join(" <= "));
  check(
    "so diversity moves the two risks in opposite directions and there is no m that minimises both",
    floorMonotone && forkMonotone,
    "the object floor falls from " + formatPercent(floors.get(1)!) + " to " + formatPercent(floors.get(35)!) + " while forks rise from " + formatPercent(forks.get(1)!) + " to " + formatPercent(forks.get(35)!),
  );

  const baseNoM: Omit<MetaConfig, "implementations"> = { validators: 35, threshold: 18, commonModeRate: RHO, independentRate: P, interpretationDivergence: D, seed: 7 };
  const best1 = optimalImplementations(baseNoM, candidates, 1);
  const best10 = optimalImplementations(baseNoM, candidates, 10);
  const best30 = optimalImplementations(baseNoM, candidates, 30);
  out("| fork severity | optimal implementations |");
  out("|---------------|-------------------------|");
  out("| 1 | " + best1 + " |");
  out("| 10 | " + best10 + " |");
  out("| 30 | " + best30 + " |");
  out("");
  check(
    "the optimum shifts toward a single implementation as a fork gets more expensive",
    best1 > 1 && best10 >= 1 && best30 <= best10,
    "severity 1 -> m=" + best1 + ", severity 10 -> m=" + best10 + ", severity 30 -> m=" + best30,
  );
  check(
    "and at a high enough fork cost diversity is net-negative, leaving m=1",
    best30 === 1,
    "severity 30 -> m=" + best30,
  );

  // -------------------------------------------------------------------------
  out("## Conclusion");
  out("");
  out("**1. Frequency turns a tolerable per-round rate into a near-certain lifetime event.**");
  out("A shared cause at 0.2 that a streaming system averages away gives a 50% chance of");
  out("capturing an amendment within three attempts and 99% within twenty-one. The chain does");
  out("not need the cause to persist; it only needs it to coincide.");
  out("");
  out("**2. Persistence makes the damage unbounded rather than bounded.** At the object level");
  out("the bad-round fraction converges on p/(p+c) - about 18% here - because a later");
  out("transition under unchanged rules can correct it. At the meta level capture is");
  out("absorbing and the fraction converges on 100%. The same per-event rate, roughly five");
  out("times the lifetime damage, growing with the protocol's age.");
  out("");
  out("**3. Diversity is a safety win at the object level and a fork risk at the meta level.**");
  out("The floor falls as implementations are added and the chance that they read the rules");
  out("differently rises. There is no m that minimises both.");
  out("");
  out("**4. The design conclusion is uncomfortable but clear.** If a fork of the rules is");
  out("expensive - and it should be, since it splits the chain's common ground - the optimum");
  out("is a SINGLE implementation with the effort put into making that implementation correct,");
  out("not into validator count or diversity. A self-amending chain can have self-amendment or");
  out("implementation diversity, and it cannot have both.");
  out("");
  out("That is a boundary result against the naive plan. It says the interesting engineering");
  out("problem is not the consensus mechanism; it is reducing the shared-cause rate of one");
  out("implementation, plus designing an amendment procedure unambiguous enough that");
  out("independent readers cannot diverge on it.");
  out("");

  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, "meta-consensus.md"), lines.join("\n"), "utf8");
  console.log("");
  console.log("meta-consensus: " + (failures.length === 0 ? "all claims held" : failures.length + " claim(s) FAILED") + " -> experiments/results/meta-consensus.md");
  if (failures.length > 0) process.exitCode = 1;
}

main();
