import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Domain } from "../../kernel/domain.ts";
import { createIntegrityVerifier } from "../../kernel/evidence.ts";
import { policyDocument } from "../../kernel/policy.ts";
import type { JsonValue, TransitionProposal } from "../../kernel/types.ts";
import { genesisPolicy, standardInterpreter, standardPreconditions } from "../../extensions/index.ts";
import {
  AC_UNIT,
  accountValue,
  coinKey,
  createCoinEffect,
  lock,
  settleLocked,
  totalOf,
  transfer,
  updateCoinEffect,
  type CoinValue,
} from "../../extensions/coin.ts";
import { checkCoinSupply, expectedLossInAc, formatAc, supplyOf } from "./model.ts";

const resultsDir = join(dirname(fileURLToPath(import.meta.url)), "..", "results");
const failures: string[] = [];
const lines: string[] = [];

function out(text = ""): void {
  lines.push(text);
}

function check(claim: string, held: boolean, detail: string): void {
  if (!held) failures.push(claim + " - " + detail);
  console.log((held ? "  ok   " : "  FAIL ") + claim + (detail ? "  [" + detail + "]" : ""));
}

const PAY_POLICY = policyDocument({
  id: "pay",
  description: "a transfer must preserve the supply and keep every account well formed",
  rules: [{ type: "coin-supply-preserving-effect" }, { type: "coin-non-negative-effect" }],
});

const MINT_POLICY = policyDocument({
  id: "mint",
  description: "issuance is explicit, capped, and limited to the treasury",
  rules: [
    { type: "actor-in", params: { actors: ["treasury"] } },
    { type: "coin-supply-at-most", params: { limit: 100 } },
    { type: "coin-non-negative-effect" },
  ],
});

function coinDomain(id: string, balances: Record<string, number>, policies: readonly ReturnType<typeof policyDocument>[]): Domain {
  return new Domain({
    id,
    interpreter: standardInterpreter(),
    verifier: createIntegrityVerifier(),
    preconditions: standardPreconditions(),
    clock: () => 1,
    initialState: [
      ...policies.map((policy) => genesisPolicy(policy)),
      ...Object.entries(balances).map(([owner, amount]) => ({
        key: coinKey(owner),
        version: 1,
        value: accountValue(amount) as unknown as JsonValue,
        createdBy: "sha256:genesis",
        updatedBy: "sha256:genesis",
        createdAt: 0,
        updatedAt: 0,
      })),
    ],
  });
}

function payment(domain: Domain, actor: string, from: string, to: string, amount: number, policyId = "pay"): TransitionProposal {
  const fromDoc = domain.document(coinKey(from))!;
  const toDoc = domain.document(coinKey(to))!;
  const moved = transfer(fromDoc.value as unknown as CoinValue, toDoc.value as unknown as CoinValue, amount);
  if (!moved.ok) throw new Error("transfer refused: " + moved.reason);
  return {
    id: "pay-" + from + "-" + to + "-" + amount,
    domain: domain.id,
    actor,
    intent: "pay " + amount + " " + AC_UNIT + " from " + from + " to " + to,
    policy: { id: policyId },
    preconditions: [],
    effects: [updateCoinEffect(fromDoc, moved.from), updateCoinEffect(toDoc, moved.to)],
    evidence: [],
    parents: [],
    createdAt: 1,
  };
}

function mint(domain: Domain, actor: string, owner: string, amount: number, id = "mint-1"): TransitionProposal {
  const existing = domain.document(coinKey(owner));
  const value = existing ? (existing.value as unknown as CoinValue) : accountValue(0);
  const next: CoinValue = { ...value, balance: value.balance + amount };
  return {
    id,
    domain: domain.id,
    actor,
    intent: "issue " + amount + " " + AC_UNIT + " to " + owner,
    policy: { id: "mint" },
    preconditions: [],
    effects: [existing ? updateCoinEffect(existing, next) : createCoinEffect(coinKey(owner), next)],
    evidence: [],
    parents: [],
    createdAt: 1,
  };
}

function coinOf(domain: Domain, owner: string): CoinValue {
  return domain.document(coinKey(owner))!.value as unknown as CoinValue;
}

function main(): void {
  out("# A-Coin");
  out("");
  out("Generated by experiments/a-coin/run.ts.");
  out("");
  out("A-Coin is the protocol framework's own unit of account: a higher-level state schema, not");
  out("a kernel primitive, exactly as the freeze requires. What matters about it is not the");
  out("schema - a balance is a number - but the invariant it carries.");
  out("");
  out("> The total supply is a SHARED UNIQUENESS INVARIANT.");
  out("");
  out("Two independent domains can each mint A-Coin for the same agent and neither is internally");
  out("inconsistent. That is the freeze's own condition for when shared state is required, so");
  out("A-Coin is the first thing in this project that NEEDS a chain rather than merely allowing");
  out("one.");
  out("");

  // -------------------------------------------------------------------------
  console.log("1. Conservation inside a domain");
  const domain = coinDomain("ledger", { alice: 100, bob: 0, escrow: 0 }, [PAY_POLICY]);
  const genesisSupply = supplyOf(domain.state.documents.values());

  const pay = domain.propose(payment(domain, "alice", "alice", "bob", 40));
  const aliceAfterPay = coinOf(domain, "alice");
  const bobAfterPay = coinOf(domain, "bob");

  // escrow: spendable becomes locked, total unchanged
  const aliceDoc = domain.document(coinKey("alice"))!;
  const locked = lock(aliceAfterPay, 50);
  const lockResult = domain.propose({
    id: "lock-1",
    domain: "ledger",
    actor: "alice",
    intent: "escrow 50 AC",
    policy: { id: "pay" },
    preconditions: [],
    effects: [updateCoinEffect(aliceDoc, locked.ok ? locked.value : aliceAfterPay)],
    evidence: [],
    parents: [],
    createdAt: 1,
  });
  const aliceAfterLock = coinOf(domain, "alice");

  // settle: locked leaves the account. This must be refused by the pay policy.
  const aliceDoc2 = domain.document(coinKey("alice"))!;
  const settled = settleLocked(aliceAfterLock, 50);
  const settleResult = domain.propose({
    id: "settle-1",
    domain: "ledger",
    actor: "alice",
    intent: "settle the escrow out of existence",
    policy: { id: "pay" },
    preconditions: [],
    effects: [updateCoinEffect(aliceDoc2, settled.ok ? settled.value : aliceAfterLock)],
    evidence: [],
    parents: [],
    createdAt: 1,
  });

  const report = checkCoinSupply(domain);
  out("## 1. Conservation inside a domain");
  out("");
  out("| transition | committed | supply |");
  out("|------------|-----------|--------|");
  out("| genesis | - | " + formatAc(genesisSupply) + " |");
  out("| pay 40 alice -> bob | " + (pay.committed ? "yes" : "no") + " | " + formatAc(supplyOf(domain.state.documents.values())) + " |");
  out("| escrow 50 from alice | " + (lockResult.committed ? "yes" : "no") + " | " + formatAc(supplyOf(domain.state.documents.values())) + " |");
  out("| settle 50 out of existence (pay policy) | " + (settleResult.committed ? "yes" : "no") + " | " + formatAc(supplyOf(domain.state.documents.values())) + " |");
  out("");
  check("a payment moves value without changing the supply", pay.committed && totalOf(bobAfterPay) === 40 && totalOf(aliceAfterPay) === 60, "alice 60, bob 40");
  check("escrow moves spendable to locked, still without changing the supply", lockResult.committed && aliceAfterLock.balance === 10 && aliceAfterLock.locked === 50, JSON.stringify(aliceAfterLock));
  check("the transfer rule refuses a transition that would destroy value", settleResult.committed === false && settleResult.failure?.kind === "POLICY", String(settleResult.failure?.detail));
  check("and the domain invariant confirms the supply never moved", report.ok && report.supply === genesisSupply && report.leaked === 0, report.reason);

  // -------------------------------------------------------------------------
  console.log("");
  console.log("2. Issuance is explicit and auditable");
  const issuing = coinDomain("issuing", { treasury: 0, carol: 0 }, [PAY_POLICY, MINT_POLICY]);
  const legit = issuing.propose(mint(issuing, "treasury", "carol", 60, "mint-legit"));
  const overCap = issuing.propose(mint(issuing, "treasury", "carol", 60, "mint-over-cap"));
  const byOutsider = issuing.propose(mint(issuing, "mallory", "mallory", 10, "mint-outsider"));
  const issuingReport = checkCoinSupply(issuing);
  out("## 2. Issuance is explicit and auditable");
  out("");
  out("| attempt | actor | committed | reason |");
  out("|---------|-------|-----------|--------|");
  out("| issue 60 AC | treasury | " + (legit.committed ? "yes" : "no") + " | " + (legit.committed ? "supply below the cap" : String(legit.failure?.detail)) + " |");
  out("| issue 60 more | treasury | " + (overCap.committed ? "yes" : "no") + " | " + String(overCap.failure?.detail ?? "-") + " |");
  out("| issue 10 AC | mallory | " + (byOutsider.committed ? "yes" : "no") + " | " + String(byOutsider.failure?.detail ?? "-") + " |");
  out("");
  check("the treasury can issue up to the cap", legit.committed === true && issuingReport.issued === 60, "issued " + issuingReport.issued + " AC");
  check("the cap stops further issuance", overCap.committed === false && overCap.failure?.kind === "POLICY", String(overCap.failure?.detail));
  check("an unauthorised issuer cannot mint", byOutsider.committed === false && byOutsider.failure?.kind === "POLICY", String(byOutsider.failure?.detail));
  check("the ledger invariant accounts for issuance exactly", issuingReport.ok && issuingReport.supply === issuingReport.expected, "genesis " + issuingReport.genesis + " + issued " + issuingReport.issued + " = " + issuingReport.supply);

  // -------------------------------------------------------------------------
  console.log("");
  console.log("3. The shared-invariant result");
  const left = coinDomain("domain-left", { treasury: 0, agentx: 0 }, [PAY_POLICY, MINT_POLICY]);
  const right = coinDomain("domain-right", { treasury: 0, agentx: 0 }, [PAY_POLICY, MINT_POLICY]);
  const leftMint = left.propose(mint(left, "treasury", "agentx", 100, "mint-left"));
  const rightMint = right.propose(mint(right, "treasury", "agentx", 100, "mint-right"));
  const leftHolds = coinOf(left, "agentx").balance;
  const rightHolds = coinOf(right, "agentx").balance;

  const shared = coinDomain("domain-shared", { treasury: 0, agentx: 0 }, [PAY_POLICY, MINT_POLICY]);
  const sharedFirst = shared.propose(mint(shared, "treasury", "agentx", 100, "mint-shared-1"));
  const sharedSecond = shared.propose(mint(shared, "treasury", "agentx", 100, "mint-shared-2"));
  const sharedReport = checkCoinSupply(shared);

  out("## 3. The shared-invariant result");
  out("");
  out("The SAME mint policy text, evaluated in two independent domains and in one shared domain:");
  out("");
  out("| domain | first issue | second issue | agent-x holds |");
  out("|--------|-------------|--------------|---------------|");
  out("| domain-left | " + (leftMint.committed ? "100 AC" : "refused") + " | - | " + formatAc(leftHolds) + " |");
  out("| domain-right | " + (rightMint.committed ? "100 AC" : "refused") + " | - | " + formatAc(rightHolds) + " |");
  out("| domain-shared | " + (sharedFirst.committed ? "100 AC" : "refused") + " | " + (sharedSecond.committed ? "100 AC" : "refused") + " | " + formatAc(coinOf(shared, "agentx").balance) + " |");
  out("");
  check(
    "two independent domains both issue the full cap for the same agent",
    leftMint.committed === true && rightMint.committed === true && leftHolds === 100 && rightHolds === 100,
    "agent-x appears to hold " + (leftHolds + rightHolds) + " AC while the intended supply is 100",
  );
  check(
    "neither domain is internally inconsistent, which is the whole problem",
    checkCoinSupply(left).ok && checkCoinSupply(right).ok,
    "both ledgers satisfy their own supply invariant",
  );
  check(
    "one shared domain refuses the second issue",
    sharedFirst.committed === true && sharedSecond.committed === false,
    String(sharedSecond.failure?.detail),
  );
  check(
    "so a supply cap is only meaningful where every account is visible",
    sharedReport.ok && sharedReport.supply === 100,
    "shared supply is exactly " + sharedReport.supply + " AC",
  );
  out("");
  out("This is the freeze's principle instantiated by the currency:");
  out("");
  out("> A shared uniqueness invariant requires a shared semantic domain.");
  out("");
  out("A-Coin is therefore the reason to build the chain. Every other schema in this repository");
  out("- commitments, capabilities, outcomes, identities - works fine inside one domain. The");
  out("supply does not.");
  out("");

  // -------------------------------------------------------------------------
  console.log("");
  console.log("4. A-Coin as the measurement unit");
  out("## 4. A-Coin as the measurement unit");
  out("");
  out("Every rate this repository measures becomes a figure in A-Coin once it is attached to");
  out("value at risk. Escrow of 300 AC per decision, cost model release 1.00 / deny 0.05 /");
  out("failure 0.10.");
  out("");
  out("Rates are copied from the generated reports: the correlated floors from");
  out("@@experiments/results/validator-quorum.md@@ and the judge rates from");
  out("@@experiments/results/judge-bench.md@@.");
  out("");
  out("| configuration | source | false AFFIRM | expected loss per decision |");
  out("|---------------|--------|--------------|----------------------------|");
  const escrow = 300;
  const rows: Array<{ label: string; source: string; rate: number }> = [
    { label: "one validator, correlated at rho=0.2", source: "validator-quorum", rate: 0.323 },
    { label: "3 validators k=2, correlated", source: "validator-quorum", rate: 0.253 },
    { label: "7 validators k=4, correlated", source: "validator-quorum", rate: 0.209 },
    { label: "3 validators k=2, independent", source: "validator-quorum", rate: 0.063 },
    { label: "qwen2.5:1.5b as judge", source: "judge-bench", rate: 2 / 12 },
    { label: "decision-4b as judge", source: "judge-bench", rate: 1 / 12 },
  ];
  const losses = new Map<string, number>();
  for (const row of rows) {
    const loss = expectedLossInAc({ falseAffirmRate: row.rate, falseDenyRate: 0, failRate: 0 }, escrow);
    losses.set(row.label, loss);
    out("| " + row.label + " | " + row.source + " | " + (row.rate * 100).toFixed(1) + "% | **" + formatAc(loss) + "** |");
  }
  out("");
  check(
    "a purpose-built decision model beats a correlated validator quorum on cost",
    losses.get("decision-4b as judge")! < losses.get("7 validators k=4, correlated")!,
    formatAc(losses.get("decision-4b as judge")!) + " against " + formatAc(losses.get("7 validators k=4, correlated")!),
  );
  check(
    "independence beats correlation at the same quorum size",
    losses.get("3 validators k=2, independent")! < losses.get("3 validators k=2, correlated")!,
    formatAc(losses.get("3 validators k=2, independent")!) + " against " + formatAc(losses.get("3 validators k=2, correlated")!),
  );
  check(
    "and the whole repository's results are now legible in one unit",
    losses.size === rows.length,
    rows.length + " configurations priced in " + AC_UNIT,
  );

  // -------------------------------------------------------------------------
  out("## Conclusion");
  out("");
  out("**1. A-Coin is an extension schema, and it is the one that needs a chain.** Conservation");
  out("   is enforced by a policy rule for transfers and by a ledger invariant for issuance, so");
  out("   neither a careless transition nor a mislabelled one can change the supply unnoticed.");
  out("");
  out("**2. The supply is a genuinely shared invariant.** The same mint policy is correct in a");
  out("   shared domain and double-counts across two independent ones, with both ledgers");
  out("   internally consistent. That is the freeze's condition for shared state, satisfied.");
  out("");
  out("**3. A-Coin is an instrument, not a feature.** Once value at risk is denominated in AC,");
  out("   every earlier result - a judge's false-affirm rate, a quorum's correlated floor -");
  out("   becomes a cost per decision. The purpose-built decision model costs " +
    formatAc(losses.get("decision-4b as judge")!) +
    " per decision against " +
    formatAc(losses.get("7 validators k=4, correlated")!) +
    " for a seven-validator correlated quorum.");
  out("");

  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, "a-coin.md"), lines.join("\n"), "utf8");
  console.log("");
  console.log("a-coin: " + (failures.length === 0 ? "all claims held" : failures.length + " claim(s) FAILED") + " -> experiments/results/a-coin.md");
  if (failures.length > 0) process.exitCode = 1;
}

main();
