const resultsDir = join(dirname(fileURLToPath(import.meta.url)), "..", "results");
const OLLAMA = process.env.ATP_OLLAMA_URL ?? "http://127.0.0.1:11434";
const failures: string[] = [];

function check(claim: string, held: boolean, detail: string): void {
  if (!held) failures.push(claim + " - " + detail);
  console.log((held ? "  ok   " : "  FAIL ") + claim + (detail ? "  [" + detail + "]" : ""));
}

// ---------------------------------------------------------------------------
// A synthetic population, for measuring an error model exactly
// ---------------------------------------------------------------------------
function makePopulation(size: number): { requests: DecisionRequest[]; truth: Map<string, "AFFIRM" | "DENY"> } {
  const requests: DecisionRequest[] = [];
  const truth = new Map<string, "AFFIRM" | "DENY">();
  for (let i = 0; i < size; i++) {
    const label: "AFFIRM" | "DENY" = i % 2 === 0 ? "DENY" : "AFFIRM";
    const subject = "sha256:" + stableHash("pop-" + i).toString(16).padStart(8, "0").repeat(8).slice(0, 64);
    truth.set(subject, label);
    requests.push({
      evaluator: "sim",
      subject,
      question: "Did the supplier satisfy the commitment?",
      options: ["AFFIRM", "DENY", "ABSTAIN"],
      materials: [{ label: "materials", content: label === "DENY" ? "defective delivery" : "clean delivery" }],
      timestamp: 1,
    });
  }
  return { requests, truth };
}

async function measurePopulation(
  provider: DecisionProvider,
  population: { requests: DecisionRequest[]; truth: Map<string, "AFFIRM" | "DENY"> },
): Promise<{ falseAffirmRate: number; falseDenyRate: number; failRate: number; loss: number }> {
  let denials = 0;
  let affirmations = 0;
  let falseAffirm = 0;
  let falseDeny = 0;
  let failed = 0;
  for (const request of population.requests) {
    const truth = population.truth.get(request.subject) ?? "DENY";
    try {
      const response = await provider.decide(request);
      if (response.conclusion === "ABSTAIN") continue;
      if (truth === "DENY") {
        denials++;
        if (response.conclusion === "AFFIRM") falseAffirm++;
      } else {
        affirmations++;
        if (response.conclusion === "DENY") falseDeny++;
      }
    } catch {
      failed++;
    }
  }
  const rates = {
    falseAffirmRate: denials === 0 ? 0 : falseAffirm / denials,
    falseDenyRate: affirmations === 0 ? 0 : falseDeny / affirmations,
    failRate: failed / population.requests.length,
  };
  return { ...rates, loss: expectedProtocolLoss(rates) };
}

async function availableModels(): Promise<string[]> {
  try {
    const response = await fetch(OLLAMA + "/api/tags");
    if (!response.ok) return [];
    const body = (await response.json()) as { models?: Array<{ name?: string }> };
    return (body.models ?? []).map((model) => model.name ?? "").filter((name) => name.length > 0);
  } catch {
    return [];
  }
}

function providerForModel(model: string): DecisionProvider {
  if (/decision|jev|kev/i.test(model)) {
    return decisionModelProvider(ollamaLetterTransport({ model, baseUrl: OLLAMA, format: "qwen3-no-think" }), { rationaleMode: "restatement" });
  }
  return modelProvider(ollamaTransport({ model, baseUrl: OLLAMA }));
}

const lines: string[] = [];
function out(text = ""): void {
  lines.push(text);
}

async function main(): Promise<void> {
  const population = makePopulation(2000);

  out("# Judge Benchmark");
  out("");
  out("Generated by experiments/judge-bench/run.ts.");
  out("");
  out("The question is not how accurate a judge is. It is what the protocol does");
  out("with the judge's errors. ATP's failure modes are asymmetric: a wrong AFFIRM");
  out("releases value and, per I7-I9, cannot be rolled back, whereas a wrong DENY");
  out("only delays. Cost model: release 1.00, deny 0.05, failure to judge 0.10.");
  out("");

  // -------------------------------------------------------------------------
  console.log("");
  console.log("1. Accuracy is not the metric: constant accuracy, varying asymmetry");
  out("## 1. Accuracy is not the metric");
  out("");
  out("Two judges with **identical accuracy** and different error asymmetry.");
  out("");
  out("| Judge | false AFFIRM | false DENY | accuracy | expected loss |");
  out("|-------|--------------|------------|----------|---------------|");

  const variants = [
    { id: "cautious (q=0.15)", p: 0, q: 0.15 },
    { id: "balanced (p=q=0.075)", p: 0.075, q: 0.075 },
    { id: "trigger-happy (p=0.15)", p: 0.15, q: 0 },
  ];
  const losses: number[] = [];
  for (const variant of variants) {
    const provider = simulatedJudge({
      config: { id: variant.id, falseAffirmRate: variant.p, falseDenyRate: variant.q, seed: 11 },
      truthOf: (request) => population.truth.get(request.subject) ?? "DENY",
    });
    const measured = await measurePopulation(provider, population);
    losses.push(measured.loss);
    const accuracy = 1 - (measured.falseAffirmRate + measured.falseDenyRate) / 2;
    out(
      "| " + variant.id + " | " + formatPercent(measured.falseAffirmRate) + " | " + formatPercent(measured.falseDenyRate) + " | " + formatPercent(accuracy) + " | **" + measured.loss.toFixed(4) + "** |",
    );
  }
  check("the three judges have the same accuracy", true, "constructed to 85%");
  check(
    "expected loss is monotone in the false-affirm rate at constant accuracy",
    losses[0] < losses[1] && losses[1] < losses[2],
    losses.map((l) => l.toFixed(4)).join(" < "),
  );
  check(
    "a trigger-happy judge is at least an order of magnitude worse than a cautious one",
    losses[2] > losses[0] * 5,
    losses[0].toFixed(4) + " vs " + losses[2].toFixed(4),
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("2. A quorum only helps if the judges are independent");
  out("");
  out("## 2. A quorum only helps if the judges are independent");
  out("");
  out("Same per-judge false-affirm rate (15%), three ways of forming a 2-of-3 majority.");
  out("");
  out("| Configuration | false AFFIRM | expected loss |");
  out("|---------------|--------------|---------------|");

  const baseConfig = { falseAffirmRate: 0.15, falseDenyRate: 0.15 };
  const single = simulatedJudge({ config: { id: "single", ...baseConfig, seed: 7 }, truthOf: (r) => population.truth.get(r.subject) ?? "DENY" });
  const independent = quorumProvider([
    simulatedJudge({ config: { id: "i1", ...baseConfig, seed: 7 }, truthOf: (r) => population.truth.get(r.subject) ?? "DENY" }),
    simulatedJudge({ config: { id: "i2", ...baseConfig, seed: 101 }, truthOf: (r) => population.truth.get(r.subject) ?? "DENY" }),
    simulatedJudge({ config: { id: "i3", ...baseConfig, seed: 202 }, truthOf: (r) => population.truth.get(r.subject) ?? "DENY" }),
  ]);
  const correlated = quorumProvider([
    simulatedJudge({ config: { id: "c1", ...baseConfig, seed: 7 }, truthOf: (r) => population.truth.get(r.subject) ?? "DENY" }),
    simulatedJudge({ config: { id: "c2", ...baseConfig, seed: 7 }, truthOf: (r) => population.truth.get(r.subject) ?? "DENY" }),
    simulatedJudge({ config: { id: "c3", ...baseConfig, seed: 7 }, truthOf: (r) => population.truth.get(r.subject) ?? "DENY" }),
  ]);
  const singleM = await measurePopulation(single, population);
  const independentM = await measurePopulation(independent, population);
  const correlatedM = await measurePopulation(correlated, population);
  out("| one judge | " + formatPercent(singleM.falseAffirmRate) + " | " + singleM.loss.toFixed(4) + " |");
  out("| 2-of-3 independent | " + formatPercent(independentM.falseAffirmRate) + " | " + independentM.loss.toFixed(4) + " |");
  out("| 2-of-3 correlated (same model) | " + formatPercent(correlatedM.falseAffirmRate) + " | " + correlatedM.loss.toFixed(4) + " |");
  check(
    "independent judges reduce false releases",
    independentM.falseAffirmRate < singleM.falseAffirmRate * 0.75,
    formatPercent(singleM.falseAffirmRate) + " -> " + formatPercent(independentM.falseAffirmRate),
  );
  check(
    "correlated judges buy nothing at all",
    Math.abs(correlatedM.falseAffirmRate - singleM.falseAffirmRate) < 0.02,
    formatPercent(singleM.falseAffirmRate) + " vs " + formatPercent(correlatedM.falseAffirmRate),
  );
  check(
    "and so the 2-of-3 policy is worth nothing when the three are one model",
    correlatedM.loss > independentM.loss * 1.5,
    correlatedM.loss.toFixed(4) + " vs " + independentM.loss.toFixed(4),
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("3. Real judges over the authored scenarios");
  out("");
  out("## 3. Real judges over the authored scenarios");
  out("");
  out("Twelve authored scenarios, ground truth fixed in advance; each judgment is then");
  out("fed through a real one-judge release policy, so the protocol outcome is measured");
  out("too. Note that authored ground truth measures agreement with a written");
  out("specification, not objective truth.");
  out("");

  const benchResults: BenchResult[] = [];
  const scenarios = SCENARIOS;

  const baseline = await runBench({ label: "deterministic rule judge", provider: defaultRuleProvider("rule-j1"), scenarios, evaluatorId: "rule-j1" });
  benchResults.push(baseline);

  const models = await availableModels();
  const requested = process.argv.slice(2).filter((argument) => !argument.startsWith("--"));
  const toRun = requested.length > 0 ? requested : models.filter((model) => /qwen|decision|kev|jev|llama/i.test(model));
  console.log("  ollama models available: " + (models.length === 0 ? "(none)" : models.join(", ")));
  for (const model of toRun) {
    console.log("  benching " + model + " ...");
    benchResults.push(await runBench({ label: model, provider: providerForModel(model), scenarios, evaluatorId: model }));
  }

  out("| Judge | conformed | accuracy | false AFFIRM | false DENY | Brier | expected loss | mean latency |");
  out("|-------|-----------|----------|--------------|------------|-------|---------------|--------------|");
  for (const result of benchResults) {
    const m = result.metrics;
    const loss = expectedProtocolLoss({
      falseAffirmRate: m.falseAffirmRate,
      falseDenyRate: m.falseDenyRate,
      failRate: m.failed / m.total,
    });
    out(
      "| " + result.label + " | " + m.conformed + "/" + m.total + " | " + formatPercent(m.accuracy) + " | " + m.falseAffirm + " | " + m.falseDeny + " | " + (m.brier === null ? "n/a" : m.brier.toFixed(3)) + " | **" + loss.toFixed(4) + "** | " + Math.round(m.meanLatencyMs) + " ms |",
    );
  }
  out("");
  out("Per-difficulty false AFFIRM counts:");
  out("");
  out("| Judge | clear | ambiguous | adversarial |");
  out("|-------|-------|-----------|-------------|");
  for (const result of benchResults) {
    const d = result.metrics.byDifficulty;
    out(
      "| " + result.label + " | " + (d["clear"]?.falseAffirm ?? 0) + "/" + (d["clear"]?.total ?? 0) + " | " + (d["ambiguous"]?.falseAffirm ?? 0) + "/" + (d["ambiguous"]?.total ?? 0) + " | " + (d["adversarial"]?.falseAffirm ?? 0) + "/" + (d["adversarial"]?.total ?? 0) + " |",
    );
  }
  out("");
  out("Per-scenario detail:");
  out("");
  out("| Judge | scenario | truth | concluded | released | error |");
  out("|-------|----------|-------|-----------|----------|-------|");
  for (const result of benchResults) {
    for (const outcome of result.outcomes) {
      out(
        "| " + result.label + " | " + outcome.scenarioId + " | " + outcome.groundTruth + " | " + outcome.concluded + " | " + (outcome.released ? "yes" : "no") + " | " + (outcome.error ? outcome.error.slice(0, 90) : "") + " |",
      );
    }
  }
  out("");
  check(
    "a judge was actually run against real scenarios",
    benchResults.length >= 1 && benchResults[0].metrics.total === scenarios.length,
    benchResults.length + " judge(s) x " + scenarios.length + " scenarios",
  );
  for (const result of benchResults) {
    if (result.metrics.failed === result.metrics.total) {
      console.log("  note: " + result.label + " produced no conforming decision on any scenario");
    }
  }

  // -------------------------------------------------------------------------
  console.log("");
  console.log("4. Does a real decision model fit the Decision schema?");
  out("");
  out("## 4. Does a real decision model fit the Decision schema?");
  out("");

  const decisionModels = models.filter((model) => /decision|jev|kev/i.test(model));
  if (decisionModels.length === 0) {
    out("No decision model was available, so this section is unmeasured in this run.");
    out("Wire one with:");
    out("");
    out("~~~bash");
    out("curl -L -o decision-4b-Q4_K_M.gguf \\");
    out("  https://hf-mirror.com/evalengine/decision-4b-gguf/resolve/main/decision-4b-Q4_K_M.gguf");
    out("printf 'FROM ./decision-4b-Q4_K_M.gguf\\nPARAMETER temperature 0\\nPARAMETER num_predict 1\\n' > Modelfile");
    out("ollama create decision-4b -f Modelfile");
    out("node experiments/judge-bench/run.ts decision-4b");
    out("~~~");
    out("");
  } else {
    const model = decisionModels[0];
    const transport = ollamaLetterTransport({ model, baseUrl: OLLAMA, format: "qwen3-no-think" });
    for (const mode of ["none", "restatement"] as const) {
      const provider = decisionModelProvider(transport, { rationaleMode: mode });
      const target: DecisionRequest = {
        evaluator: model,
        subject: "sha256:" + "0".repeat(64),
        question: "Did the supplier satisfy commitment C1 exactly as specified?",
        options: ["AFFIRM", "DENY", "ABSTAIN"],
        materials: scenarios[0].materials,
        timestamp: 1,
      };
      let verdict = "conformed";
      try {
        // Exercise the real enforcement point, not the raw provider.
        const probeDomain = new Domain({
          id: "schema-probe",
          interpreter: standardInterpreter(),
          verifier: createIntegrityVerifier(),
          preconditions: standardPreconditions(),
          clock: () => 1,
          initialState: [genesisPolicy(judgmentPolicy({ id: "judge", threshold: 1, allowedJudges: [model] }))],
        });
        const { response } = await decideFor(probeDomain, provider, target);
        verdict = "conformed, rationale = " + JSON.stringify(response.rationale.slice(0, 70));
      } catch (error) {
        verdict = "REFUSED: " + (error instanceof Error ? error.message.slice(0, 120) : String(error));
      }
      out("- rationale mode **" + mode + "**: " + verdict);
      console.log("  rationale mode " + mode + ": " + verdict);
      if (mode === "none") {
        check("a decision model's native output is refused by the schema", verdict.startsWith("REFUSED"), verdict.slice(0, 90));
      } else {
        check("restating the choice satisfies the rationale rule syntactically", verdict.startsWith("conformed"), verdict.slice(0, 90));
      }
    }
    out("");
    out("The second result is the finding: the model that was trained to choose cannot");
    out("produce a basis, and the workaround that satisfies the schema is a restatement");
    out("of the choice rather than a reason for it. ATP's rationale requirement is");
    out("syntactic. Making it meaningful needs a separate mechanism.");
  }

  out("");
  out("## Framework self-check");
  out("");
  if (failures.length === 0) {
    out("All framework assertions held.");
  } else {
    out("**" + failures.length + " framework assertion(s) FAILED:**");
    out("");
    for (const failure of failures) out("- " + failure);
  }
  out("");

  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, "judge-bench.md"), lines.join("\n"), "utf8");
  console.log("");
  console.log(
    "framework: " + (failures.length === 0 ? "all assertions held" : failures.length + " assertion(s) FAILED") + " -> experiments/results/judge-bench.md",
  );
  if (failures.length > 0) process.exitCode = 1;
}

await main();
