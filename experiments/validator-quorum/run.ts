import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  analyticFloor,
  binomialTail,
  familySizes,
  formatPercent,
  majority,
  marginalErrorRate,
  simulate,
  type QuorumConfig,
} from "./model.ts";

const resultsDir = join(dirname(fileURLToPath(import.meta.url)), "..", "results");
const P = 0.15;
const ROUNDS = 40000;
const BIG_ROUNDS = 20000;

const failures: string[] = [];
const lines: string[] = [];

function out(text = ""): void {
  lines.push(text);
}

function check(claim: string, held: boolean, detail: string): void {
  if (!held) failures.push(claim + " - " + detail);
  console.log((held ? "  ok   " : "  FAIL ") + claim + (detail ? "  [" + detail + "]" : ""));
}

function config(over: Partial<QuorumConfig> = {}): QuorumConfig {
  return { validators: 3, threshold: 2, commonModeRate: 0, independentRate: P, families: 1, seed: 7, ...over };
}

function main(): void {
  out("# Validator Quorum Under Correlated Failure");
  out("");
  out("Generated by experiments/validator-quorum/run.ts.");
  out("");
  out("ATP-0002 says selection over valid successors is a domain-level mechanism and says");
  out("nothing about whether it is safe. This measures what its safety actually depends on.");
  out("");
  out("Two error sources, separated on purpose:");
  out("");
  out("- a **shared cause** that hits a whole client family and flips every member (a bug in");
  out("  the shared client, an ambiguous rule, a coordinated input);");
  out("- **independent noise** at " + P + " per validator.");
  out("");
  out("A validator is one that runs R and votes. Ground truth is 50/50 valid and invalid.");
  out("**False accept** is a quorum canonicalising an invalid transition - the dangerous");
  out("direction, because in ATP-0002 selection is not rolled back. **False reject** costs");
  out("only liveness.");
  out("");

  // -------------------------------------------------------------------------
  console.log("1. The correlated floor");
  out("## 1. The correlated floor");
  out("");
  out("P(false accept) for a majority quorum, one client family. The right-hand column is the");
  out("exact probability that shared causes alone force acceptance.");
  out("");
  out("| rho | n=1 | n=3 (k=2) | n=5 (k=3) | n=7 (k=4) | analytic floor, n=7 |");
  out("|-----|-----|-----------|-----------|-----------|---------------------|");

  const rhos = [0, 0.05, 0.1, 0.2, 0.35, 0.5];
  const sweep = new Map<number, Map<number, number>>();
  for (const rho of rhos) {
    const row = new Map<number, number>();
    const cells: string[] = [];
    for (const n of [1, 3, 5, 7]) {
      const cfg = config({ validators: n, threshold: majority(n), commonModeRate: rho, families: 1 });
      const measured = simulate(cfg, ROUNDS).falseAcceptRate;
      row.set(n, measured);
      cells.push(formatPercent(measured));
    }
    sweep.set(rho, row);
    out("| " + rho.toFixed(2) + " | " + cells.join(" | ") + " | " + formatPercent(analyticFloor(config({ validators: 7, threshold: 4, commonModeRate: rho }))) + " |");
  }
  out("");

  const ind = sweep.get(0)!;
  const ratio = ind.get(1)! / ind.get(3)!;
  const p = P;
  const theoretical = p / (3 * p * p * (1 - p) + p ** 3);
  check(
    "2-of-3 buys about two and a half times, not orders of magnitude",
    ratio > 2 && ratio < 3,
    formatPercent(ind.get(1)!) + " -> " + formatPercent(ind.get(3)!) + " = " + ratio.toFixed(2) + "x; closed form predicts " + theoretical.toFixed(2) + "x",
  );

  let floorHolds = true;
  let floorDetail = "";
  for (const rho of rhos) {
    for (const n of [1, 3, 5, 7]) {
      const measured = sweep.get(rho)!.get(n)!;
      if (measured + 1e-9 < rho * 0.97) {
        floorHolds = false;
        floorDetail = "rho=" + rho + " n=" + n + " measured " + measured.toFixed(4);
      }
    }
  }
  check("false acceptance is floored at the shared-cause rate for every quorum size", floorHolds, floorDetail === "" ? "held for all 24 configurations" : floorDetail);

  let monotone = true;
  for (const n of [1, 3, 5, 7]) {
    for (let index = 1; index < rhos.length; index++) {
      if (sweep.get(rhos[index])!.get(n)! < sweep.get(rhos[index - 1])!.get(n)! - 0.01) monotone = false;
    }
  }
  check("false acceptance is monotone in the shared-cause rate", monotone, "no configuration inverted");

  const half = sweep.get(0.5)!;
  check(
    "at rho = 0.5 the quorum is indistinguishable from one validator",
    Math.abs(half.get(7)! - half.get(1)!) < 0.08,
    formatPercent(half.get(1)!) + " vs " + formatPercent(half.get(7)!),
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("2. Raising the threshold does not fix correlation");
  out("## 2. Raising the threshold does not fix correlation");
  out("");
  out("Three validators, three thresholds.");
  out("");
  out("| rho | k=1 | k=2 | k=3 (unanimous) |");
  out("|-----|-----|-----|-----------------|");
  for (const rho of [0, 0.1, 0.3]) {
    out(
      "| " + rho.toFixed(2) + " | " +
        [1, 2, 3].map((k) => formatPercent(simulate(config({ validators: 3, threshold: k, commonModeRate: rho }), ROUNDS).falseAcceptRate)).join(" | ") +
        " |",
    );
  }
  out("");
  const uni0 = simulate(config({ validators: 3, threshold: 3, commonModeRate: 0 }), ROUNDS);
  const maj0 = simulate(config({ validators: 3, threshold: 2, commonModeRate: 0 }), ROUNDS);
  const uni3 = simulate(config({ validators: 3, threshold: 3, commonModeRate: 0.3 }), ROUNDS);
  const maj3 = simulate(config({ validators: 3, threshold: 2, commonModeRate: 0.3 }), ROUNDS);
  check("unanimity is far safer than majority when validators are independent", uni0.falseAcceptRate < maj0.falseAcceptRate * 0.2, formatPercent(uni0.falseAcceptRate) + " vs " + formatPercent(maj0.falseAcceptRate));
  check("at rho = 0.3 unanimity buys almost nothing", uni3.falseAcceptRate > maj3.falseAcceptRate * 0.8, formatPercent(uni3.falseAcceptRate) + " vs " + formatPercent(maj3.falseAcceptRate));
  check("and it costs liveness for that non-benefit", uni0.falseRejectRate > maj0.falseRejectRate * 2, "false reject " + formatPercent(uni0.falseRejectRate) + " vs " + formatPercent(maj0.falseRejectRate));

  // -------------------------------------------------------------------------
  console.log("");
  console.log("3. The floor is set by the LARGEST family");
  out("## 3. The floor is set by the largest family");
  out("");
  out("Seven validators, majority (k=4), rho = 0.2. The design rule that falls out is:");
  out("");
  out("> **No client family may hold at least as many validators as the threshold.**");
  out("");
  out("A family that holds k members is one shared cause away from the threshold on its own.");
  out("");
  out("| families | split | max family | >= k? | P(false accept) | analytic floor |");
  out("|----------|-------|------------|-------|-----------------|----------------|");

  const diversity = new Map<number, { measured: number; floor: number; maxFamily: number }>();
  for (const families of [1, 2, 3, 5, 7]) {
    const cfg = config({ validators: 7, threshold: 4, commonModeRate: 0.2, families });
    const sizes = familySizes(cfg);
    const maxFamily = Math.max(...sizes);
    const measured = simulate(cfg, ROUNDS).falseAcceptRate;
    const floor = analyticFloor(cfg);
    diversity.set(families, { measured, floor, maxFamily });
    out(
      "| " + families + " | " + sizes.join("+") + " | " + maxFamily + " | " + (maxFamily >= 4 ? "yes" : "no") + " | " + formatPercent(measured) + " | " + formatPercent(floor) + " |",
    );
  }
  out("");
  check("one family is a shared cause from the threshold on its own", diversity.get(1)!.maxFamily >= 4 && Math.abs(diversity.get(1)!.floor - 0.2) < 1e-9, "floor " + formatPercent(diversity.get(1)!.floor));
  check(
    "a two-way split leaves a family of exactly k, so the floor does not move",
    diversity.get(2)!.maxFamily >= 4 && Math.abs(diversity.get(2)!.floor - diversity.get(1)!.floor) < 1e-9,
    "floor " + formatPercent(diversity.get(1)!.floor) + " -> " + formatPercent(diversity.get(2)!.floor) + " for a 4+3 split",
  );
  check(
    "and it is measurably WORSE, because a three-member cause plus one independent flip also reaches k",
    diversity.get(2)!.measured > diversity.get(1)!.measured * 1.2,
    formatPercent(diversity.get(1)!.measured) + " -> " + formatPercent(diversity.get(2)!.measured),
  );
  check(
    "the floor drops as soon as every family is below k",
    diversity.get(3)!.maxFamily < 4 && diversity.get(3)!.floor < diversity.get(2)!.floor * 0.75,
    "floor " + formatPercent(diversity.get(2)!.floor) + " -> " + formatPercent(diversity.get(3)!.floor) + " at 3+2+2",
  );
  check(
    "more families keep lowering it",
    diversity.get(7)!.floor < diversity.get(5)!.floor && diversity.get(5)!.floor < diversity.get(3)!.floor,
    formatPercent(diversity.get(3)!.floor) + " > " + formatPercent(diversity.get(5)!.floor) + " > " + formatPercent(diversity.get(7)!.floor),
  );
  check(
    "but at n=7 the independent path keeps the measured value well above the floor",
    diversity.get(7)!.measured > diversity.get(7)!.floor * 3,
    "floor " + formatPercent(diversity.get(7)!.floor) + " but measured " + formatPercent(diversity.get(7)!.measured),
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("4. The floor is a bound, not a prediction");
  out("## 4. The floor is a bound, not a prediction");
  out("");
  out("Same rho = 0.2, now 35 validators with k = 18, so a shared cause needs help to reach");
  out("the threshold unless one family is large enough on its own.");
  out("");
  out("| families | max family | P(false accept) | analytic floor | gap over floor |");
  out("|----------|------------|-----------------|----------------|----------------|");
  const big = new Map<number, number>();
  for (const families of [1, 5, 7, 35]) {
    const cfg = config({ validators: 35, threshold: 18, commonModeRate: 0.2, families });
    const measured = simulate(cfg, BIG_ROUNDS).falseAcceptRate;
    big.set(families, measured);
    const floor = analyticFloor(cfg);
    out(
      "| " + families + " | " + Math.max(...familySizes(cfg)) + " | " + formatPercent(measured) + " | " + formatPercent(floor) + " | " +
        (measured - floor >= 0 ? "+" : "") + ((measured - floor) * 100).toFixed(1) + " |",
    );
  }
  out("");
  const floorOf = (m: number) => analyticFloor(config({ validators: 35, threshold: 18, commonModeRate: 0.2, families: m }));
  check(
    "the floor is tight when one family can carry the threshold by itself",
    Math.abs(big.get(1)! - floorOf(1)) < 0.02,
    formatPercent(big.get(1)!) + " against a floor of " + formatPercent(floorOf(1)),
  );
  check(
    "where causes must combine, independent noise fills the shortfall and the floor is loose",
    big.get(5)! - floorOf(5) > 0.05 && big.get(7)! - floorOf(7) > 0.05,
    "gap of " + ((big.get(5)! - floorOf(5)) * 100).toFixed(1) + " points at 5 families, " + ((big.get(7)! - floorOf(7)) * 100).toFixed(1) + " at 7",
  );
  check(
    "absolute risk still falls monotonically as implementations are diversified",
    big.get(1)! > big.get(5)! && big.get(5)! > big.get(7)! && big.get(7)! > big.get(35)!,
    [1, 5, 7, 35].map((m) => formatPercent(big.get(m)!)).join(" > "),
  );
  const marginal = marginalErrorRate(config({ commonModeRate: 0.2 }));
  const predicted = binomialTail(35, marginal, 18);
  check(
    "and the residual at full diversity is the marginal error rate's binomial tail, not synchronisation",
    Math.abs(big.get(35)! - predicted) < 0.009,
    formatPercent(big.get(35)!) + " measured against " + formatPercent(predicted) + " predicted from q = rho + (1-rho)p = " + formatPercent(marginal),
  );

  // -------------------------------------------------------------------------
  console.log("");
  console.log("5. The exchange rate");
  out("## 5. The exchange rate between validators and diversity");
  out("");
  out("Single-family quorums at rho = 0.2 against a small diverse one. Can validator count");
  out("substitute for diversity?");
  out("");
  out("| configuration | P(false accept) |");
  out("|---------------|-----------------|");
  for (const n of [1, 3, 5, 7, 9, 15, 31]) {
    out("| n=" + n + ", 1 family | " + formatPercent(simulate(config({ validators: n, threshold: majority(n), commonModeRate: 0.2, families: 1 }), ROUNDS).falseAcceptRate) + " |");
  }
  const smallDiverse = simulate(config({ validators: 5, threshold: 3, commonModeRate: 0.2, families: 5 }), ROUNDS).falseAcceptRate;
  out("| n=5, 5 families | " + formatPercent(smallDiverse) + " |");
  out("");
  const n31 = simulate(config({ validators: 31, threshold: 16, commonModeRate: 0.2, families: 1 }), ROUNDS).falseAcceptRate;
  check("same-family validators saturate at the floor", Math.abs(n31 - diversity.get(1)!.measured) < 0.02, formatPercent(diversity.get(1)!.measured) + " (n=7) vs " + formatPercent(n31) + " (n=31)");
  check(
    "and a small diverse quorum is barely better than a large correlated one",
    smallDiverse > n31 * 0.85,
    formatPercent(smallDiverse) + " (n=5 diverse) vs " + formatPercent(n31) + " (n=31 correlated); both sit near the floor",
  );
  check(
    "so diversity and size must be raised together",
    big.get(35)! < n31 * 0.1,
    formatPercent(big.get(35)!) + " at n=35 diverse against " + formatPercent(n31) + " at n=31 correlated",
  );

  // -------------------------------------------------------------------------
  out("## Conclusion");
  out("");
  out("The study refuted its own first hypothesis, which is the useful part.");
  out("");
  out("**1. False acceptance is floored at the shared-cause rate.** Held across all 24");
  out("configurations of the first sweep. When a shared cause fires, every member of the");
  out("affected family flips and the quorum accepts regardless of its threshold.");
  out("");
  out("**2. The floor is set by the largest family, not by the number of families.** This was");
  out("the surprise. Splitting seven validators at k=4 into 4+3 does not move the floor at all,");
  out("because a four-member family is still one shared cause from the threshold - and the");
  out("split is measurably WORSE (20.9% to 28.4%), because a three-member cause plus a single");
  out("independent flip now also reaches k. The design rule that follows:");
  out("");
  out("> **No client family may hold at least as many validators as the threshold.**");
  out("");
  out("**3. The floor is a bound, not a prediction.** It is tight only when one family can");
  out("carry the threshold by itself. Where causes must combine, independent noise fills the");
  out("shortfall: at five families two causes give 14 votes and four more have to come from");
  out("noise, so the realised risk is 13.7% against a floor of 5.8%.");
  out("");
  out("**4. Diversity de-correlates; it does not reduce the marginal error rate.** At full");
  out("diversity the floor is zero but the residual is not - every validator still carries its");
  out("own family's shared cause, so the marginal error is rho + (1-rho)p, 32% here, and");
  out("reaching 18 of 35 is a binomial tail: 1.6% measured against 1.1% predicted from that");
  out("tail alone. Diversity and a low shared-cause rate are two different requirements.");
  out("");
  out("**5. Threshold is not a strictness parameter.** Unanimity is far safer than majority");
  out("when validators are independent, buys almost nothing at rho = 0.3, and quadruples");
  out("false rejections.");
  out("");
  out("For ATP-0002 this is a boundary result. The freeze correctly says selection is not a");
  out("kernel property, so the kernel cannot be blamed for any of it. It also means **a");
  out("chain's safety claim cannot come from ATP-0002 and cannot come from validator count or");
  out("stake. It comes from implementation diversity, which is an ecosystem property.** A");
  out("chain that ships one client has a safety floor equal to its shared-cause rate, and no");
  out("number of validator slots or staked tokens moves it.");
  out("");

  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, "validator-quorum.md"), lines.join("\n"), "utf8");
  console.log("");
  console.log("quorum study: " + (failures.length === 0 ? "all claims held" : failures.length + " claim(s) FAILED") + " -> experiments/results/validator-quorum.md");
  if (failures.length > 0) process.exitCode = 1;
}

main();
