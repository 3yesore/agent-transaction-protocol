import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { renderMarkdown } from "./harness.ts";
import { runCrossAgentAtomicity } from "./exp-001-cross-agent-atomicity.ts";
import { runMaliciousJudge } from "./exp-003-malicious-judge.ts";
import { runOverCommitment } from "./exp-004-overcommitment.ts";
import { runOutcomeReversal } from "./exp-005-outcome-reversal.ts";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "results");
mkdirSync(outDir, { recursive: true });

const runs = [
  { file: "exp-001-cross-agent-atomicity.md", report: runCrossAgentAtomicity() },
  { file: "exp-003-malicious-judge.md", report: runMaliciousJudge() },
  { file: "exp-004-overcommitment.md", report: runOverCommitment() },
  { file: "exp-005-outcome-reversal.md", report: runOutcomeReversal() },
];

const summary: string[] = [];
summary.push("# ATP Experiment Summary");
summary.push("");
summary.push("Generated by experiments/run-all.ts. Do not edit by hand.");
summary.push("");
summary.push("| Experiment | Assertions | Failed | Findings | Report |");
summary.push("|------------|------------|--------|----------|--------|");

let failures = 0;
for (const run of runs) {
  const markdown = renderMarkdown(run.report);
  writeFileSync(join(outDir, run.file), markdown, "utf8");
  const failed = run.report.assertions.filter((a) => !a.held).length;
  failures += failed;
  const kernel = run.report.findings.filter((f) => f.classification.indexOf("KERNEL") >= 0).length;
  summary.push(
    "| " + run.report.id + " " + run.report.title + " | " + run.report.assertions.length + " | " + failed + " | " + run.report.findings.length + " (" + kernel + " kernel/open) | [" + run.file + "](./" + run.file + ") |",
  );
  console.log(
    run.report.id + ": " + run.report.assertions.length + " assertions, " + failed + " failed, " + run.report.findings.length + " findings -> results/" + run.file,
  );
}
summary.push("");
summary.push(failures === 0 ? "All assertions held." : failures + " assertion(s) FAILED.");
summary.push("");
writeFileSync(join(outDir, "SUMMARY.md"), summary.join("\n"), "utf8");
console.log("wrote results/SUMMARY.md");

if (failures > 0) process.exitCode = 1;
