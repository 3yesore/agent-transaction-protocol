import type { Domain } from "../kernel/domain.ts";
import { checkInvariants } from "../kernel/invariants.ts";
import type { JsonValue, StateDocument } from "../kernel/types.ts";

export interface Assertion {
  readonly claim: string;
  readonly held: boolean;
  readonly detail: string;
}

export interface StepLog {
  readonly n: number;
  readonly domain: string;
  readonly actor: string;
  readonly action: string;
  readonly result: string;
}

/** Genesis state used to seed a domain before its first transition. */
export function seed(key: string, value: JsonValue, by = "sha256:genesis"): StateDocument {
  return { key, version: 1, value, createdBy: by, updatedBy: by, createdAt: 0, updatedAt: 0 };
}

export class Recorder {
  readonly steps: StepLog[] = [];
  readonly assertions: Assertion[] = [];
  readonly domains: Domain[] = [];
  #n = 0;

  track<T extends Domain>(domain: T): T {
    this.domains.push(domain);
    return domain;
  }

  step(domain: string, actor: string, action: string, result: string): void {
    this.steps.push({ n: ++this.#n, domain, actor, action, result });
  }

  assert(claim: string, held: boolean, detail = ""): void {
    this.assertions.push({ claim, held, detail });
  }

  allPassed(): boolean {
    return this.assertions.every((a) => a.held);
  }

  domainReport(): string[] {
    return this.domains.map((d) => {
      const v = d.verify();
      return d.id + ": " + d.ledger.length + " transition(s), " + (v.ok ? "verified" : "BROKEN - " + v.reason);
    });
  }

  invariantReport(): string[] {
    const lines: string[] = [];
    for (const domain of this.domains) {
      for (const report of checkInvariants(domain)) {
        if (report.status === "FAIL") lines.push(domain.id + " " + report.id + " FAIL - " + report.detail);
      }
    }
    if (lines.length === 0) lines.push("no invariant violations across " + this.domains.length + " domain(s)");
    return lines;
  }
}

export interface ReviewCase {
  readonly id: string;
  readonly name: string;
  /** The candidate claim this case tries to refute. */
  readonly invariant: string;
  /** A falsifiable prediction. If it fails, the candidate claim is REFUTED. */
  readonly prediction: string;
  readonly scenario: string;
  readonly observed: string;
  readonly verdict: "SUPPORTED" | "REFUTED";
  readonly classification: string;
  readonly steps: readonly StepLog[];
  readonly assertions: readonly Assertion[];
  readonly domains: readonly string[];
  readonly invariants: readonly string[];
}

export function finalize(input: {
  readonly id: string;
  readonly name: string;
  readonly invariant: string;
  readonly prediction: string;
  readonly scenario: string;
  readonly observed: string;
  readonly classification: string;
  readonly rec: Recorder;
}): ReviewCase {
  return {
    id: input.id,
    name: input.name,
    invariant: input.invariant,
    prediction: input.prediction,
    scenario: input.scenario,
    observed: input.observed,
    verdict: input.rec.allPassed() ? "SUPPORTED" : "REFUTED",
    classification: input.classification,
    steps: input.rec.steps,
    assertions: input.rec.assertions,
    domains: input.rec.domainReport(),
    invariants: input.rec.invariantReport(),
  };
}

export function renderReviewMarkdown(cases: readonly ReviewCase[]): string {
  const refuted = cases.filter((c) => c.verdict === "REFUTED").length;
  const lines: string[] = [];
  lines.push("# ATP v0.2 Candidate - Executable Adversarial Review");
  lines.push("");
  lines.push(
    "Generated by experiments/v0.2-review/run.ts. Each case states a falsifiable prediction about the candidate kernel, runs it, and is REFUTED if an assertion fails.",
  );
  lines.push("");
  lines.push("**Cases:** " + cases.length + "  |  **Supported:** " + (cases.length - refuted) + "  |  **Refuted:** " + refuted);
  lines.push("");
  lines.push("| # | Case | Tests | Verdict |");
  lines.push("|---|------|-------|---------|");
  for (const c of cases) {
    lines.push("| " + c.id + " | " + c.name + " | " + c.invariant + " | " + (c.verdict === "SUPPORTED" ? "supported" : "**REFUTED**") + " |");
  }
  lines.push("");
  for (const c of cases) {
    lines.push("## " + c.id + " - " + c.name);
    lines.push("");
    lines.push("**Tests:** " + c.invariant);
    lines.push("");
    lines.push("**Prediction:** " + c.prediction);
    lines.push("");
    lines.push("**Scenario:** " + c.scenario);
    lines.push("");
    lines.push("**Observed:** " + c.observed);
    lines.push("");
    lines.push("**Verdict:** " + (c.verdict === "SUPPORTED" ? "supported" : "**REFUTED**") + "  |  **Classification:** " + c.classification);
    lines.push("");
    lines.push("| # | Domain | Actor | Action | Result |");
    lines.push("|---|--------|-------|--------|--------|");
    for (const s of c.steps) {
      lines.push("| " + s.n + " | " + s.domain + " | " + s.actor + " | " + s.action + " | " + s.result + " |");
    }
    lines.push("");
    lines.push("| Assertion | Held | Detail |");
    lines.push("|-----------|------|--------|");
    for (const a of c.assertions) {
      lines.push("| " + a.claim + " | " + (a.held ? "yes" : "**NO**") + " | " + a.detail + " |");
    }
    lines.push("");
    lines.push("Domain verification:");
    lines.push("");
    for (const d of c.domains) lines.push("- " + d);
    lines.push("");
    lines.push("Invariant checks:");
    lines.push("");
    for (const i of c.invariants) lines.push("- " + i);
    lines.push("");
  }
  return lines.join("\n");
}
